"""Export a rule set to Drools DRL.

Rules share one activation-group so only the highest-salience match fires,
which mirrors RuleForge's own first-match-by-priority semantics. Types are
declared inline so the file loads into a KIE base with no Java model.
"""
from __future__ import annotations

from .dictionary import DataDictionary
from .ir import RuleSet

JAVA_TYPES = {"int": "int", "bool": "boolean", "enum": "String", "code_list": "java.util.List"}


def camel(name: str) -> str:
    head, *tail = name.split("_")
    return head + "".join(t.capitalize() for t in tail)


def _lit(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return '"' + str(v).replace('"', '\\"') + '"'


def _expr(node: dict) -> str:
    if "field" in node:
        f, op, v = camel(node["field"]), node["op"], node["value"]
        if op in {"==", "!=", "<", "<=", ">", ">="}:
            return f"{f} {op} {_lit(v)}"
        if op == "in":
            return f"{f} in ({', '.join(map(_lit, v))})"
        if op == "not_in":
            return f"{f} not in ({', '.join(map(_lit, v))})"
        if op == "includes_any":
            return "(" + " || ".join(f"{f} contains {_lit(c)}" for c in v) + ")"
        if op == "includes_none":
            return "(" + " && ".join(f"{f} not contains {_lit(c)}" for c in v) + ")"
        raise ValueError(op)
    if "all" in node:
        return "(" + " && ".join(_expr(c) for c in node["all"]) + ")"
    if "any" in node:
        return "(" + " || ".join(_expr(c) for c in node["any"]) + ")"
    if "not" in node:
        return "!(" + _expr(node["not"]) + ")"
    raise ValueError(node)


def to_drl(ruleset: RuleSet, dd: DataDictionary, package: str = "com.example.policy") -> str:
    out = [f"package {package};", "", "// Generated by RuleForge. Do not edit by hand; regenerate from policy.", ""]
    out.append("declare ClaimRequest")
    for f in dd.fields.values():
        out.append(f"    {camel(f.name)} : {JAVA_TYPES[f.type]}")
    out += ["end", "", "declare Decision", "    outcome : String", "    reasonCode : String",
            "    ruleId : String", "end", ""]
    for r in ruleset.ordered():
        quote = " ".join(r.source_quote.split())
        out += [
            f'rule "{r.id}: {r.description}"',
            f"    // source: \"{quote}\"",
            f"    salience {r.priority}",
            '    activation-group "policy-decision"',
            "when",
            f"    $c : ClaimRequest( {_expr(r.when)} )",
            "then",
            f'    insert(new Decision("{r.decision}", "{r.reason_code}", "{r.id}"));',
            "end",
            "",
        ]
    return "\n".join(out)
